"""Generate the manuscript tables from the pinned result files (task E4); nothing in a table is typed by hand.

generated/tab_maps.tex  : held-out population vs context-only at h = 1, per family and r: each map's own n grid, the largest
                          n whose lower bound (estimate - 3 SE) is >= delta, the gap range there, and the number of
                          BORDERLINE cells whose point estimate is already >= delta (cells the map cannot resolve).
generated/tab_delta.tex : sensitivity of the largest identifiable n to delta in {0.01, 0.02, 0.04} (r = 1), same files.
"""

from __future__ import annotations

import csv
import importlib.util
import io
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
BS = "\\"


def _bc():
    spec = importlib.util.spec_from_file_location("build_claims", ROOT / "paper" / "tools" / "build_claims.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["build_claims"] = mod
    spec.loader.exec_module(mod)
    return mod


def rows(bc, data, key):
    f = data["files"][key]
    raw, _ = bc.git_blob(data["refs"][f["ref"]], f["path"])
    if raw is None:
        raise SystemExit(f"FAIL: {key} missing at its pinned commit")
    if f["path"].endswith(".gz"):
        import gzip
        raw = gzip.decompress(raw)
    return list(csv.DictReader(io.StringIO(raw.decode("utf-8"))))


def per_draw_table(bc, data, delta: float = 0.02) -> list[str]:
    """Share of (held-out cell, library draw) pairs in which lib vs pop is separable (lower bound >= delta), per family and
    library size K. 1A and F1: the per-cell `frac_lo_ge_delta` of the decisions files, averaged over cells; F3 (h = 1, by q)
    and F2: per-draw rows of the map_rows files, lower bound = mean - 3 se (F2's se includes the Monte Carlo part)."""
    out = {}
    for key, label in (("map1a", "AR(1), known $" + BS + "sigma$"), ("f1map", "AR(1), unknown $" + BS + "sigma$")):
        cells = [r for r in rows(bc, data, key) if r["set"] == "HELD" and r["pair"] == "lib|pop"]
        seen, uniq = set(), []
        for c in cells:
            if (c["r"], c["n"], c["K"]) not in seen:
                seen.add((c["r"], c["n"], c["K"]))
                uniq.append(c)
        for k in sorted({int(c["K"]) for c in uniq}):
            fr = [float(c["frac_lo_ge_delta"]) for c in uniq if int(c["K"]) == k]
            out.setdefault(label, {})[k] = sum(fr) / len(fr)
    f3 = [r for r in rows(bc, data, "f3rows") if r["set"] == "HELD" and r["pair"] == "pop-lib" and r["h"] == "1"]
    for q in ("0.0", "6.5"):
        sub = [r for r in f3 if r["q"] == q]
        for k in sorted({int(r["K"]) for r in sub}):
            v = [float(r["mean"]) - 3.0 * float(r["se"]) >= delta for r in sub if int(r["K"]) == k]
            out.setdefault(f"noisy AR(1), $q={q}$", {})[k] = sum(v) / len(v)
    f2 = [r for r in rows(bc, data, "f2rows") if r["set"] == "HELD" and r["pair"] == "pop-lib"]
    for k in sorted({int(r["K"]) for r in f2}):
        v = [float(r["mean"]) - 3.0 * float(r["se"]) >= delta for r in f2 if int(r["K"]) == k]
        out.setdefault("bivariate VAR(1)", {})[k] = sum(v) / len(v)
    ks = sorted({k for d in out.values() for k in d})
    nl = f" {BS}{BS}"
    lines = ["% generated by paper/tools/make_tables.py (per-draw library agreement); do not edit",
             f"{BS}begin{{tabular}}{{l" + "c" * len(ks) + "}", f"{BS}toprule",
             "Family & " + " & ".join(f"$K={k}$" for k in ks) + nl, f"{BS}midrule"]
    for label, d in out.items():
        lines.append(label + " & " + " & ".join(f"{100 * d[k]:.0f}" if k in d else "" for k in ks) + nl)
    lines += [f"{BS}bottomrule", f"{BS}end{{tabular}}"]
    return lines


def lower(c: dict) -> float:
    """estimate - 3 SE: the 1A and F1 files store it as `lo`; the F3 file stores `se`."""
    if c.get("lo", "") != "":
        return float(c["lo"])
    return float(c["estimate"]) - 3.0 * float(c["se"])


def summarise(cells: list[dict], delta: float = 0.02) -> tuple[str, str, str]:
    """(separable window, gap range there or the largest gap, notes). MC-LIMITED cells (F2) are never counted as
    separable, whatever their bound; they are listed in the notes. The separable set is printed as "n <= k" only when
    it is every grid point up to k, otherwise as an explicit set; a star marks a window that reaches the last grid point
    (end not mapped)."""
    grid = sorted({int(float(c["n"])) for c in cells})
    mc = sorted(int(float(c["n"])) for c in cells if c.get("decision") == "MC-LIMITED")
    cells = [c for c in cells if c.get("decision") != "MC-LIMITED"]
    ident = [c for c in cells if lower(c) >= delta]
    near = sum(1 for c in cells if lower(c) < delta <= float(c["estimate"]))
    notes = [f"{near} borderline with estimate ${BS}ge{BS}delta$"] if near else []
    notes += [f"MC-limited at $n={','.join(map(str, mc))}$"] if mc else []
    if not ident:
        return "none", f"max {max(float(c['estimate']) for c in cells):.3f}", "; ".join(notes)
    ns = sorted({int(float(c["n"])) for c in ident})
    star = "^{*}" if ns[-1] == grid[-1] else ""
    window = (f"n{BS}le {ns[-1]}" if ns == [g for g in grid if g <= ns[-1]]
              else f"n{BS}in{BS}{{{','.join(map(str, ns))}{BS}}}")
    lo = min(float(c["estimate"]) for c in ident)
    hi = max(float(c["estimate"]) for c in ident)
    return f"${window}{star}$", f"{lo:.3f}--{hi:.3f}", "; ".join(notes)


def largest_n(cells: list[dict], delta: float) -> str:
    grid = max(int(float(c["n"])) for c in cells)
    ident = [int(float(c["n"])) for c in cells if c.get("decision") != "MC-LIMITED" and lower(c) >= delta]
    if not ident:
        return "--"
    return f"{max(ident)}$^{{*}}$" if max(ident) == grid else str(max(ident))


def main() -> int:
    bc = _bc()
    data = yaml.safe_load((ROOT / "paper" / "numbers.yaml").read_text(encoding="utf-8"))
    m1a = [r for r in rows(bc, data, "map1a") if r["set"] == "HELD" and r["pair"] == "pop|stab"]
    seen = set()
    m1a = [r for r in m1a if (r["r"], r["n"]) not in seen and not seen.add((r["r"], r["n"]))]
    f1 = [r for r in rows(bc, data, "f1map") if r["set"] == "HELD" and r["pair"] == "pop|ctx"]
    f3 = [r for r in rows(bc, data, "f3map") if r["pair"] == "pop-stab" and r["h"] == "1"]
    families = [(f"AR(1), known ${BS}sigma$ (1A map)", m1a), (f"AR(1), unknown ${BS}sigma$ (F1 map)", f1)]
    for q in ("0.0", "0.755", "2.56", "6.5"):
        families.append((f"noisy AR(1), $q={q}$ (F3 map)", [r for r in f3 if r["q"] == q]))
    f2 = [r for r in rows(bc, data, "f2map") if r["set"] == "HELD" and r["pair"] == "pop-ctx"]
    families.append(("bivariate VAR(1) (F2 map)", f2))
    nl = f" {BS}{BS}"
    lines = ["% generated by paper/tools/make_tables.py from the pinned map files; do not edit",
             f"{BS}begin{{tabular}}{{llcllp{{2.8cm}}}}", f"{BS}toprule",
             f"Family & $n$ grid & $r$ & separable & gap (nats) & notes{nl}", f"{BS}midrule"]
    for k, (name, cells) in enumerate(families):
        grid = ",".join(str(v) for v in sorted({int(float(c["n"])) for c in cells}))
        if k:
            lines.append(f"{BS}addlinespace")
        for j, rv in enumerate((0.25, 1.0, 4.0)):
            window, gaps, notes = summarise([c for c in cells if float(c["r"]) == rv])
            head = f"{name} & ${BS}{{{grid}{BS}}}$" if j == 0 else " & "
            lines.append(f"{head} & {rv:g} & {window} & {gaps} & {notes}{nl}")
    lines += [f"{BS}bottomrule", f"{BS}end{{tabular}}"]
    deltas = (0.01, 0.02, 0.04)
    sl = ["% generated by paper/tools/make_tables.py (delta sensitivity); do not edit", f"{BS}begin{{tabular}}{{lccc}}",
          f"{BS}toprule", "Family ($r=1$) & " + " & ".join(f"${BS}delta={d}$" for d in deltas) + nl, f"{BS}midrule"]
    for name, cells in families:
        sub = [c for c in cells if float(c["r"]) == 1.0]
        sl.append(f"{name} & " + " & ".join(largest_n(sub, d) for d in deltas) + nl)
    sl += [f"{BS}bottomrule", f"{BS}end{{tabular}}"]
    gen = ROOT / "paper" / "generated"
    gen.mkdir(exist_ok=True)
    (gen / "tab_maps.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (gen / "tab_delta.tex").write_text("\n".join(sl) + "\n", encoding="utf-8")
    pd = per_draw_table(bc, data)
    (gen / "tab_library.tex").write_text("\n".join(pd) + "\n", encoding="utf-8")
    st = sensitivity_table(bc, data)
    (gen / "tab_sensitivity.tex").write_text("\n".join(st) + "\n", encoding="utf-8")
    print("\n".join(lines + sl + pd + st))
    return 0


def sensitivity_table(bc, data) -> list[str]:
    """Largest separable n (h = 1) per r and the largest gap, for each row declared in numbers.yaml `tables.sensitivity`
    (row filters on the pinned sensitivity file); a star marks the last grid point of that row."""
    spec = data["tables"]["sensitivity"]
    allrows = rows(bc, data, spec["file"])
    nl = f" {BS}{BS}"
    out = ["% generated by paper/tools/make_tables.py (sensitivity, tables.sensitivity in numbers.yaml); do not edit",
           f"{BS}begin{{tabular}}{{llccc}}", f"{BS}toprule",
           f"Setting & variant & $r=0.25$ & $r=1$ & $r=4${nl}", f"{BS}midrule"]
    for k, row in enumerate(spec["rows"]):
        sub = [r for r in allrows if r["h"] == "1" and all(str(r[a]) == str(b) for a, b in row["where"].items())]
        if not sub:
            raise SystemExit(f"FAIL: sensitivity row {row['label']!r} matches nothing in the pinned file")
        if row.get("group") and k:
            out.append(f"{BS}addlinespace")
        cells = []
        for rv in ("0.25", "1.0", "4.0"):
            c = [r for r in sub if r["r"] == rv]
            grid = max(int(r["n"]) for r in c)
            sep = [int(r["n"]) for r in c if r["decision"] == "IDENTIFIABLE"]
            top = max(float(r["estimate"]) for r in c)
            n_txt = "--" if not sep else (f"{max(sep)}$^{{*}}$" if max(sep) == grid else str(max(sep)))
            cells.append(f"{n_txt} ({top:.3f})")
        out.append(f"{row.get('group', '')} & {row['label']} & " + " & ".join(cells) + nl)
    out += [f"{BS}bottomrule", f"{BS}end{{tabular}}"]
    return out


if __name__ == "__main__":
    raise SystemExit(main())
