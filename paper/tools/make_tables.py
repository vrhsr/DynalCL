"""Generate the manuscript tables from the pinned result files (task E4); nothing in a table is typed by hand.

generated/tab_maps.tex  : population vs context-only, held-out systems, h = 1: largest IDENTIFIABLE n and the gap range,
                          per family (Stage 1A known sigma, F1 unknown sigma, F3 noisy observations at each q) and r.
"""

from __future__ import annotations

import csv
import importlib.util
import io
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def _bc():
    spec = importlib.util.spec_from_file_location("build_claims", ROOT / "paper" / "tools" / "build_claims.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["build_claims"] = mod
    spec.loader.exec_module(mod)
    return mod


def rows(bc, data, key):
    f = data["files"][key]
    raw, commit = bc.git_blob(data["refs"][f["ref"]], f["path"])
    if raw is None:
        raise SystemExit(f"FAIL: {key} missing at its pinned commit")
    return list(csv.DictReader(io.StringIO(raw.decode("utf-8"))))


def summarise(cells: list[dict]) -> str:
    ident = [c for c in cells if c["decision"] == "IDENTIFIABLE"]
    if not ident:
        top = max(float(c["estimate"]) for c in cells)
        return f"none (max {top:.3f})"
    n = max(int(float(c["n"])) for c in ident)
    lo = min(float(c["estimate"]) for c in ident)
    hi = max(float(c["estimate"]) for c in ident)
    return f"$n\\le {n}$ ({lo:.3f}--{hi:.3f})"


def main() -> int:
    bc = _bc()
    data = yaml.safe_load((ROOT / "paper" / "numbers.yaml").read_text(encoding="utf-8"))
    m1a = [r for r in rows(bc, data, "map1a") if r["set"] == "HELD" and r["pair"] == "pop|stab"]
    f1 = [r for r in rows(bc, data, "f1map") if r["set"] == "HELD" and r["pair"] == "pop|ctx"]
    f3 = [r for r in rows(bc, data, "f3map") if r["pair"] == "pop-stab" and r["h"] == "1"]
    lines = ["% generated by paper/tools/make_tables.py from the pinned map files; do not edit",
             "\\begin{tabular}{llll}", "\\toprule",
             "Family & $r=0.25$ & $r=1$ & $r=4$ \\\\", "\\midrule"]
    seen = set()
    m1a_u = [r for r in m1a if (r["r"], r["n"]) not in seen and not seen.add((r["r"], r["n"]))]
    families = [("AR(1), known $\\sigma$ (Stage 1A map)", m1a_u, "r"), ("AR(1), unknown $\\sigma$ (F1 map)", f1, "r")]
    for q in ("0.0", "0.755", "2.56", "6.5"):
        families.append((f"noisy AR(1), $q={q}$ (F3 map)", [r for r in f3 if r["q"] == q], "r"))
    for name, cells, rk in families:
        out = [summarise([c for c in cells if float(c[rk]) == rv]) for rv in (0.25, 1.0, 4.0)]
        lines.append(f"{name} & " + " & ".join(out) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    gen = ROOT / "paper" / "generated"
    gen.mkdir(exist_ok=True)
    (gen / "tab_maps.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
