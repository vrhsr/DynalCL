"""Generate paper/generated/numbers.tex from paper/numbers.yaml (task E4).

Each macro is re-extracted from its pinned commit with the claims builder's extractors; a missing ref, path or field is a
failure (exit 1), never a silent default. Writes one \\newcommand per macro plus a provenance comment.
"""

from __future__ import annotations

import hashlib
import importlib.util
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def _claims_module():
    spec = importlib.util.spec_from_file_location("build_claims", ROOT / "paper" / "tools" / "build_claims.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["build_claims"] = mod
    spec.loader.exec_module(mod)
    return mod


def main() -> int:
    bc = _claims_module()
    data = yaml.safe_load((ROOT / "paper" / "numbers.yaml").read_text(encoding="utf-8"))
    claim_ids = {c["id"] for c in yaml.safe_load((ROOT / "paper" / "claims.yaml").read_text(encoding="utf-8"))["claims"]}
    blobs, lines, ok = {}, ["% generated by paper/tools/build_numbers.py from paper/numbers.yaml; do not edit"], True
    for key, f in data["files"].items():
        raw, commit = bc.git_blob(data["refs"][f["ref"]], f["path"])
        if raw is None or commit != data["refs"][f["ref"]]:
            print(f"FAIL: {key}: {f['ref']}:{f['path']} not found at the pinned commit")
            ok = False
            continue
        blobs[key] = raw
        lines.append(f"% {key}: {commit[:12]}:{f['path']} sha256 {hashlib.sha256(raw).hexdigest()[:16]}")
    seen = set()
    for n in data["numbers"]:
        if n["macro"] in seen or not n["macro"].isalpha():
            print(f"FAIL: macro name {n['macro']!r} duplicated or not letters only")
            ok = False
            continue
        seen.add(n["macro"])
        if n["claim"] not in claim_ids:
            print(f"FAIL: {n['macro']}: claim {n['claim']} not in claims.yaml")
            ok = False
        if n["file"] not in blobs:
            ok = False
            continue
        try:
            v = bc.extract(blobs[n["file"]], n["x"])
            if "pick" in n:
                v = v[n["pick"]]
            if "minus" in n:
                v = v - n["minus"]
            if n["fmt"] == "sci":
                mant, exp = f"{float(v):.1e}".split("e")
                text = "\\ensuremath{" + mant + "\\times 10^{" + str(int(exp)) + "}}"
            else:
                text = n["fmt"].format(v)
        except Exception as exc:
            print(f"FAIL: {n['macro']}: {type(exc).__name__}: {exc}")
            ok = False
            continue
        lines.append(f"\\newcommand{{\\{n['macro']}}}{{{text}\\xspace}}  % {n['claim']}")
    out = ROOT / "paper" / "generated"
    out.mkdir(exist_ok=True)
    (out / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"numbers.tex: {len(seen)} macros; {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
